/** 収録済み区間の開始コードポイント（昇順）。 */
const RANGE_STARTS: number[] = [];
/** 同じ添字の区間の終端コードポイント（含む）。 */
const RANGE_ENDS: number[] = [];

{
  let previousEnd = -1;
  for (const token of ENCODED_COVERAGE.split(',')) {
    const dot = token.indexOf('.');
    const start = previousEnd + 1 + Number.parseInt(token.slice(0, dot), 36);
    const end = start + Number.parseInt(token.slice(dot + 1), 36);
    RANGE_STARTS.push(start);
    RANGE_ENDS.push(end);
    previousEnd = end;
  }
}

/** テスト（表の再生成検証）から参照するための生の区間列。 */
export function coverageRanges(): readonly (readonly [number, number])[] {
  return RANGE_STARTS.map((start, i) => [start, RANGE_ENDS[i]] as const);
}

/** そのコードポイントを Noto Sans JP が描けるか（cmap に載っているか）。 */
export function isRenderableCodePoint(codePoint: number): boolean {
  let low = 0;
  let high = RANGE_STARTS.length - 1;
  while (low <= high) {
    const mid = (low + high) >> 1;
    if (codePoint < RANGE_STARTS[mid]) {
      high = mid - 1;
      continue;
    }
    if (codePoint > RANGE_ENDS[mid]) {
      low = mid + 1;
      continue;
    }
    return true;
  }
  return false;
}

// 未収録でも「落として構わない」不可視の制御・結合用コードポイント。
// 絵文字の異体字セレクタ・ZWJ・肌の色修飾子など、単体では意味を持たず、
// 〓 に置き換えると却ってノイズになるものはそのまま除去する。
function isInvisibleFormatCodePoint(codePoint: number): boolean {
  return (
    codePoint === 0x200b || // ZERO WIDTH SPACE
    codePoint === 0x200c || // ZWNJ
    codePoint === 0x200d || // ZWJ
    codePoint === 0x2060 || // WORD JOINER
    codePoint === 0xfeff || // ZWNBSP
    (codePoint >= 0xfe00 && codePoint <= 0xfe0f) || // 異体字セレクタ
    (codePoint >= 0x1f3fb && codePoint <= 0x1f3ff) || // 肌の色修飾子
    (codePoint >= 0xe0000 && codePoint <= 0xe01ef) // タグ文字・IVS
  );
}

/**
 * 未収録グリフを置き換える代替文字。〓（U+3013 GETA MARK）は日本語組版で
 * 「その文字を出せない」ことを示す伝統的な記号で、Noto Sans JP に収録済み。
 */
export const MISSING_GLYPH_PLACEHOLDER = '\u3013';

// 基本多言語面（BMP）の外。@react-pdf/renderer 4.5.x のサブセット化・エンコード経路は
// サロゲートペアを正しく扱えず、**cmap に字形がある補助面 CJK（例: 𪚲 U+2A6B2）でも**
// 無関係なグリフを送り幅 0 で描く（実測: 「𪚲 単独」→「i単独」に潰れる）。cmap 収録の
// 有無では防げないので、補助面は一律で代替表記に倒す。
const SUPPLEMENTARY_PLANE_START = 0x10000;

/** 改行・タブ・CR だけは Text 側が扱うので残す。それ以外の C0 制御文字は落とす。 */
function isLayoutControl(codePoint: number): boolean {
  return codePoint === 0x09 || codePoint === 0x0a || codePoint === 0x0d;
}

/**
 * PDF に載せる前に、登録フォントが描けない文字を安全な代替へ置き換える。
 * 描ける文字しか残らないため、無関係なグリフが重なって直後の文字まで潰す
 * （Issue #263 E）ことが構造的に起こらなくなる。制御文字は改行・タブ・CR だけを
 * 通し、残り（NUL 等）は落とす。
 */
export function toRenderableText(text: string): string {
  // ASCII だけの文字列が大半なので、走査前に安価な判定で早期リターンする。
  // `> 0x7e` だけを見ると NUL 等の C0 制御文字が素通りする（安全化の契約が崩れる）。
  let needsWork = false;
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    if (code > 0x7e || (code < 0x20 && !isLayoutControl(code))) {
      needsWork = true;
      break;
    }
  }
  if (!needsWork) return text;

  let out = '';
  for (const ch of text) {
    const codePoint = ch.codePointAt(0) ?? 0;
    // 改行・タブ・CR は Text 側で扱うのでそのまま通す（cmap には載らない）。
    if (isLayoutControl(codePoint)) {
      out += ch;
      continue;
    }
    // それ以外の C0 制御文字は、置換文字にすると見えないゴミが紙面に出るので落とす。
    if (codePoint < 0x20 || codePoint === 0x7f) continue;
    if (codePoint < SUPPLEMENTARY_PLANE_START && isRenderableCodePoint(codePoint)) {
      out += ch;
      continue;
    }
    if (isInvisibleFormatCodePoint(codePoint)) continue;
    out += MISSING_GLYPH_PLACEHOLDER;
  }
  return out;
}
