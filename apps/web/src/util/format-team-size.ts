// チーム規模の表示用フォーマット。
//
// 実データは「13 名」「9 人」等、単位込みの文字列で入っている（#136）。一方でビルダーの
// 入力欄は `placeholder="例：13"` と単位なしの数値入力を案内しており、その通りに入力すると
// 単位なしの生の数値だけが保存される。#136 で単位の二重付与（「13名名」）を解消するために
// `${item.team}名` を素の `item.team` 表示へ変えたが、単位なし数値だけはそのまま「13」と
// 出てしまい、何の数かわからなくなる（実データ回帰、レビュー指摘）。
//
// 数値のみ（前後空白を除く）のときだけ「名」を補い、それ以外（既に単位が付いている・
// 数値でない）はそのまま表示する。
export function formatTeamSize(team: string): string {
  const trimmed = team.trim();
  return /^\d+$/.test(trimmed) ? `${trimmed}名` : team;
}
